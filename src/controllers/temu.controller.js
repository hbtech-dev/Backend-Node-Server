exports.connectTemu = catchAsync(async (req, res, next) => {
  const { appKey, appSecret, accessToken, sellerId, shopName } = req.body;
  const cleanToken = (accessToken || '').trim();

  if (!cleanToken) {
    return next(new AppError('Access Token is required to connect to Temu', 400));
  }

  const mongoose = require('mongoose');
  const user = (mongoose.connection.readyState === 1 ? await User.findById(req.user.id) : null) || req.user;

  // --- Auto-resolve developer App Key & App Secret ---
  let cleanKey = (appKey || '').trim();
  let cleanSecret = (appSecret || '').trim();

  if (!cleanKey || !cleanSecret) {
    // 1. Look in existing user integrations
    const existingDev = (user.temuIntegrations || []).find(i => i.appKey && i.appSecret) || user.temuIntegration;
    if (existingDev && existingDev.appKey && existingDev.appSecret) {
      cleanKey = existingDev.appKey.trim();
      cleanSecret = existingDev.appSecret.trim();
    } else {
      // 2. Look in environment variables
      cleanKey = (process.env.TEMU_APP_KEY || '').trim();
      cleanSecret = (process.env.TEMU_APP_SECRET || '').trim();
    }
  }

  // Final check - if still not found, return descriptive error
  if (!cleanKey || !cleanSecret) {
    return next(new AppError('Developer App Credentials not configured on server. Please provide App Key & App Secret once or set them in server environment.', 400));
  }

  // --- Auto-extract Mall/Seller ID from access token ---
  // Temu tokens often end with or embed the 15-digit Mall ID
  let resolvedShopName = (shopName || '').trim();
  const mallIdMatch = cleanToken.match(/\d{10,18}/);
  if (!resolvedShopName) {
    if (mallIdMatch) {
      resolvedShopName = mallIdMatch[0];
    } else {
      resolvedShopName = `Shop-${cleanToken.slice(-6)}`;
    }
  }

  const resolvedSellerId = sellerId || (mallIdMatch ? mallIdMatch[0] : `seller-${cleanToken.slice(-6)}`);

  // ---- Attempt live Temu Open Platform Router verification ----
  const crypto = require('crypto');
  const timestamp = Math.floor(Date.now() / 1000).toString();
  const payload = {
    app_key: cleanKey,
    access_token: cleanToken,
    timestamp: timestamp,
    type: 'bg.order.list.v2.get'
  };

  const sortedKeys = Object.keys(payload).sort();
  const signStr = cleanSecret + sortedKeys.map(k => k + payload[k]).join('') + cleanSecret;
  const sign = crypto.createHash('md5').update(signStr).digest('hex').toUpperCase();

  const routerUrl = process.env.TEMU_ROUTER_URL || 'https://openapi-b-eu.temu.com/openapi/router';

  const httpFetch = require('../utils/httpHelper');

  try {
    console.log(`🔍 Connecting to Temu Router: ${routerUrl} (AppKey: ${cleanKey}, Mall: ${resolvedShopName})`);
    const testRes = await httpFetch(routerUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ ...payload, sign }),
      timeout: 8000
    });

    if (!testRes.ok) {
      console.warn(`❌ Temu router HTTP Error ${testRes.status}`);
      return next(new AppError(`Temu verification failed (HTTP ${testRes.status}). Please check your credentials and server connection.`, 401));
    }

    const body = await testRes.json();
    console.log('📋 Temu Verification Response:', JSON.stringify(body));

    // Temu Open Platform uses errorCode: 1000000 or 0 or success: true to indicate SUCCESS
    const isSuccess = body.success === true || body.errorCode === 1000000 || body.errorCode === 0;
    if (!isSuccess) {
      const errorDetail = body.errorMsg || `Error code ${body.errorCode}`;
      console.warn(`❌ Temu credentials rejected: ${errorDetail}`);
      return next(new AppError(`Invalid Temu credentials: ${errorDetail}`, 401));
    }
    console.log('✅ Temu credentials verified successfully!');
  } catch (err) {
    console.error('💥 Temu API verification exception:', err.message);
    return next(new AppError(`Temu API verification failed: ${err.message}`, 401));
  }

  // ---- Save credentials ----
  const newIntegration = {
    isConnected: true,
    appKey: cleanKey,
    appSecret: cleanSecret,
    accessToken: cleanToken,
    sellerId: resolvedSellerId,
    shopName: resolvedShopName,
    lastSyncedAt: new Date()
  };

  // Add/Update in temuIntegrations array
  // Match by accessToken only — each regional store has a UNIQUE access token
  // even though they share the same appKey. This allows connecting Spain, Germany,
  // France etc. as separate stores under the same app credentials.
  if (!user.temuIntegrations) {
    user.temuIntegrations = [];
  }
  const existingIdx = user.temuIntegrations.findIndex(i => i.accessToken === cleanToken);
  if (existingIdx > -1) {
    user.temuIntegrations[existingIdx] = newIntegration;
  } else {
    user.temuIntegrations.push(newIntegration);
  }

  // Keep single temuIntegration as fallback/backwards compatibility
  user.temuIntegration = newIntegration;

  if (mongoose.connection.readyState === 1 && typeof user.save === 'function') {
    await user.save();
    // Trigger real API sync in background — won't block the response
    const temuSyncService = require('../services/temuSync.service');
    temuSyncService.syncUserTemuOrders(user).catch(err =>
      console.warn('Post-connect Temu sync warning:', err.message)
    );
  }

  res.status(200).json({
    status: 'success',
    message: 'Temu Seller account connected! Syncing orders in background...',
    data: {
      temuIntegration: user.temuIntegration,
      temuIntegrations: user.temuIntegrations
    }
  });
});

exports.disconnectTemu = catchAsync(async (req, res, next) => {
  const mongoose = require('mongoose');
  const user = (mongoose.connection.readyState === 1 ? await User.findById(req.user.id) : null) || req.user;
  const { shopName, appKey } = req.body;

  if (shopName || appKey) {
    // Disconnect only the specified store integration
    if (user.temuIntegrations) {
      user.temuIntegrations = user.temuIntegrations.filter(
        item => item.shopName !== shopName && item.appKey !== appKey
      );
    }
    // Update fallback if it matches the disconnected store
    if (user.temuIntegration && (user.temuIntegration.shopName === shopName || user.temuIntegration.appKey === appKey)) {
      user.temuIntegration = (user.temuIntegrations && user.temuIntegrations.length > 0)
        ? user.temuIntegrations[0]
        : { isConnected: false, appKey: '', appSecret: '', sellerId: '', shopName: '', lastSyncedAt: null };
    }
  } else {
    // Clear all integrations
    user.temuIntegrations = [];
    user.temuIntegration = {
      isConnected: false,
      appKey: '',
      appSecret: '',
      sellerId: '',
      shopName: '',
      lastSyncedAt: null
      /* Do NOT delete historical order records on store disconnect */
    };

    if (mongoose.connection.readyState === 1) {
      const TemuTicket = require('../models/temuTicket.model');
      await TemuTicket.deleteMany({ user: req.user.id });
    }
  }

  if (mongoose.connection.readyState === 1 && typeof user.save === 'function') {
    await user.save();
  }

  res.status(200).json({
    status: 'success',
    message: 'Temu Store integration(s) updated successfully.',
    data: {
      temuIntegration: user.temuIntegration,
      temuIntegrations: user.temuIntegrations || []
    }
  });
});

exports.syncTemuOrders = catchAsync(async (req, res, next) => {
  const mongoose = require('mongoose');
  const userIdStr = (req.user._id || req.user.id).toString();

  // Guard: If sync is already in flight for this user, do not spawn duplicate processes
  if (activeTemuSyncs.has(userIdStr)) {
    const active = activeTemuSyncs.get(userIdStr);
    const elapsedSec = Math.round((Date.now() - active.startTime) / 1000);
    return res.status(200).json({
      status: 'success',
      message: `Temu sync is already in progress (${elapsedSec}s elapsed).`,
      data: {
        syncing: true,
        inProgress: true,
        lastSyncedAt: new Date()
      }
    });
  }

  let user = req.user;
  if (mongoose.connection.readyState === 1 && !user.temuIntegration && !user.temuIntegrations) {
    user = (await User.findById(req.user.id)) || req.user;
  }

  const isConnected = Boolean(
    (user.temuIntegration && user.temuIntegration.isConnected) || 
    (user.temuIntegrations && user.temuIntegrations.some(i => i.isConnected))
  );

  if (!isConnected) {
    return next(new AppError('Temu account is not connected. Please connect your Temu account first in Settings.', 400));
  }

  const isBackground = req.query.background === 'true' || req.body?.background === true;

  const runSync = async () => {
    activeTemuSyncs.set(userIdStr, { startTime: Date.now() });
    try {
      const temuSyncService = require('../services/temuSync.service');
      await temuSyncService.syncUserTemuOrders(user);
      if (user.temuIntegration) {
        user.temuIntegration.lastSyncedAt = new Date();
      }
      if (user.temuIntegrations && user.temuIntegrations.length > 0) {
        user.temuIntegrations.forEach(i => {
          if (i.isConnected) i.lastSyncedAt = new Date();
        });
      }
      await user.save();
    } catch (err) {
      console.error(`[Temu Sync Error for user ${userIdStr}]:`, err.message);
    } finally {
      activeTemuSyncs.delete(userIdStr);
    }
  };

  if (isBackground) {
    // Non-blocking background sync: starts immediately, returns HTTP 200 in 2ms
    runSync();
    return res.status(200).json({
      status: 'success',
      message: 'Temu background sync started.',
      data: {
        syncing: true,
        lastSyncedAt: user.temuIntegration?.lastSyncedAt || new Date()
      }
    });
  }

  await runSync();

  const ordersCount = await TemuOrder.countDocuments({ user: req.user.id, status: 'open' });

  res.status(200).json({
    status: 'success',
    message: 'Temu orders successfully synced!',
    data: {
      lastSyncedAt: user.temuIntegration?.lastSyncedAt || new Date(),
      ordersCount,
      orders: []
    }
  });
});

exports.getUserTemuOrders = catchAsync(async (req, res, next) => {
  const mongoose = require('mongoose');
  let user = req.user;

  if (mongoose.connection.readyState === 1 && !user.temuIntegration && !user.temuIntegrations) {
    user = (await User.findById(req.user.id)) || req.user;
  }
  
  const isConnected = Boolean(
    (user.temuIntegration && user.temuIntegration.isConnected) || 
    (user.temuIntegrations && user.temuIntegrations.some(i => i.isConnected))
  );

  let orders = [];
  const counts = { open: 0, created_label: 0, printed: 0, canceled: 0, total: 0 };
  let pagination = null;

  if (mongoose.connection.readyState === 1) {
    const userId = user._id || req.user.id;
    const filter = { user: userId };

    if (req.query.status) {
      filter.status = req.query.status;
    }

    if (req.query.country && req.query.country !== 'all') {
      filter.country = req.query.country.toUpperCase();
    }

    if (req.query.search && req.query.search.trim()) {
      const s = req.query.search.trim();
      filter.$or = [
        { orderNum: { $regex: s, $options: 'i' } },
        { name: { $regex: s, $options: 'i' } },
        { tracking: { $regex: s, $options: 'i' } }
      ];
    }

    const page = parseInt(req.query.page, 10);
    const limit = parseInt(req.query.limit, 10);

    let sortObj = { createdAt: -1 };
    if (filter.status === 'printed') {
      sortObj = { shippedAt: -1, updatedAt: -1, createdAt: -1 };
    }

    let query = TemuOrder.find(filter).sort(sortObj).lean();

    // Run status counts aggregation and order retrieval in parallel
    const countsPromise = TemuOrder.aggregate([
      { $match: { user: userId } },
      { $group: { _id: '$status', count: { $sum: 1 } } }
    ]);

    let ordersPromise;
    let countFilteredPromise = null;

    if (page && limit && limit > 0) {
      const skip = (page - 1) * limit;
      if ((req.query.country && req.query.country !== 'all') || req.query.search) {
        countFilteredPromise = TemuOrder.countDocuments(filter);
      }
      ordersPromise = query.skip(skip).limit(limit);
    } else {
      ordersPromise = query;
    }

    const [countsAgg, fetchedOrders, totalFiltered] = await Promise.all([
      countsPromise,
      ordersPromise,
      countFilteredPromise ? countFilteredPromise : Promise.resolve(null)
    ]);

    countsAgg.forEach(c => {
      if (c._id && counts[c._id] !== undefined) {
        counts[c._id] = c.count;
      }
      counts.total += c.count;
    });

    orders = fetchedOrders;

    if (page && limit && limit > 0) {
      const finalCount = totalFiltered !== null ? totalFiltered : (filter.status ? (counts[filter.status] || 0) : counts.total);
      pagination = {
        page,
        limit,
        totalPages: Math.max(1, Math.ceil(finalCount / limit)),
        totalCount: finalCount
      };
    }
  }

  res.status(200).json({
    status: 'success',
    data: {
      isConnected,
      lastSyncedAt: user.temuIntegration?.lastSyncedAt || new Date(),
      counts,
      pagination,
      orders
    }
  });
});

exports.getUserTemuReturns = catchAsync(async (req, res, next) => {
  const mongoose = require('mongoose');
  let user = req.user;

  if (mongoose.connection.readyState === 1) {
    user = await User.findById(req.user.id) || req.user;
  }

  // If Temu is not connected, clear sample returns and return empty list
  const isConnected = (user.temuIntegration && user.temuIntegration.isConnected) || 
                      (user.temuIntegrations && user.temuIntegrations.some(i => i.isConnected));

  if (!isConnected) {
    if (mongoose.connection.readyState === 1) {
      // Purge legacy seeded return samples
      const SAMPLE_RETURN_IDS = ['RET-076-948201', 'RET-192-384910'];
      await TemuReturn.deleteMany({ user: req.user.id, returnId: { $in: SAMPLE_RETURN_IDS } });
    }
    return res.status(200).json({
      status: 'success',
      data: { returns: [] }
    });
  }

  // Only sync returns when explicitly requested with ?sync=true
  if (req.query.sync === 'true') {
    const temuAftersalesService = require('../services/temuAftersales.service');
    if (typeof temuAftersalesService.syncAllRegionalReturns === 'function') {
      await temuAftersalesService.syncAllRegionalReturns(req.user.id).catch(err => console.warn('Aftersales sync warning:', err.message));
    }
  }

  let returnsList = [];
  if (mongoose.connection.readyState === 1) {
    const filter = { user: req.user.id };
    if (req.query.status) {
      filter.status = req.query.status;
      if (req.query.status === 'pending') {
        filter.$or = [{ temuStatusGroup: 1 }, { temuStatusGroup: { $exists: false } }];
        filter.$and = [
          { $or: [{ resolutionNotes: '' }, { resolutionNotes: null }, { resolutionNotes: { $exists: false } }] }
        ];
      }
    }
    returnsList = await TemuReturn.find(filter).sort({ createdAt: -1 }).lean();
  }

  res.status(200).json({
    status: 'success',
    data: { returns: returnsList }
  });
});

/**
 * Resolve Temu Return Request & Send Back Response to Temu
 */
exports.resolveTemuReturn = catchAsync(async (req, res, next) => {
  const { id } = req.params;
  const { action, notes, responseText, tracking, carrier } = req.body;
  const answerText = responseText || notes || `Processed ${action} via Eder App`;

  const mongoose = require('mongoose');
  if (mongoose.connection.readyState === 1) {
    const returnDoc = await TemuReturn.findOne({ _id: id, user: req.user.id }) || await TemuReturn.findOne({ returnId: id, user: req.user.id });
    if (returnDoc) {
      if (action === 'approve') returnDoc.status = 'approved';
      else if (action === 'reject') returnDoc.status = 'rejected';
      else if (action === 'refund') returnDoc.status = 'refunded';

      returnDoc.resolutionNotes = answerText;
      returnDoc.resolvedAt = new Date();
      if (tracking) returnDoc.trackingNumber = tracking;
      if (carrier) returnDoc.carrier = carrier;
      await returnDoc.save();

      if (tracking && returnDoc.orderNum) {
        const TemuOrder = require('../models/temuOrder.model');
        await TemuOrder.updateOne(
          {
            user: req.user.id,
            $or: [
              { orderNum: returnDoc.orderNum },
              { orderNum: returnDoc.orderNum.replace(/^PO-/i, '') },
              { orderNum: `PO-${returnDoc.orderNum.replace(/^PO-/i, '')}` }
            ]
          },
          {
            $set: {
              tracking,
              shippingMethod: carrier || 'DHL Paket',
              status: 'printed'
            }
          }
        ).catch(() => {});
      }

      // Submit answer & resolution to Temu Open API
      try {
        const user = await User.findById(req.user.id);
        if (user) {
          const integration = (user.temuIntegrations && user.temuIntegrations.find(i => i.isConnected)) || user.temuIntegration;
          if (integration && integration.isConnected && integration.appKey && integration.appSecret) {
            const temuSyncService = require('../services/temuSync.service');
            if (typeof temuSyncService.submitTemuReturnResolution === 'function') {
              await temuSyncService.submitTemuReturnResolution(integration, returnDoc, action, answerText);
            }
          }
        }
      } catch (apiErr) {
        console.warn('⚠️ Temu return resolution API submission warning:', apiErr.message);
      }
    }
  }

  res.status(200).json({
    status: 'success',
    message: `Return set to ${action} and resolution answer submitted to Temu API!`
  });
});

