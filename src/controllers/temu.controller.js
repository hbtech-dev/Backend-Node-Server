const processedOAuthCodes = new Map();

/**
 * OAuth Callback — Temu redirects merchants here after authorization.
 * This is a PUBLIC endpoint (no auth middleware) because the user arrives via browser redirect.
 * The user ID is carried in the `state` query parameter.
 * 
 * Flow: Temu sends ?code=XXX&state=USER_ID → we exchange code for access_token → save to DB → redirect to frontend
 */
exports.handleTemuOAuthCallback = catchAsync(async (req, res, next) => {
  const { code, state } = req.query;

  const frontendUrl = process.env.FRONTEND_URL || 'https://ederapp.de';

  if (!code) {
    console.warn('❌ Temu OAuth callback: no code received.', req.query);
    return res.redirect(`${frontendUrl}/settings?temu_error=no_code_received`);
  }

  // Handle duplicate callback requests gracefully (e.g. browser prefetch, double GET)
  if (processedOAuthCodes.has(code)) {
    const existing = processedOAuthCodes.get(code);
    if (existing && existing.status === 'success') {
      console.log(`ℹ️ Temu OAuth: Code ${code.slice(0, 8)}... already exchanged successfully. Redirecting to frontend.`);
      return res.redirect(`${frontendUrl}/settings?temu_success=true&mall_name=${encodeURIComponent(existing.mallName || '')}`);
    }
  }

  const cleanKey = (process.env.TEMU_APP_KEY || '04b2b5794465f5757a2fd5775d15a48e').replace(/['"]/g, '').trim();
  const cleanSecret = (process.env.TEMU_APP_SECRET || '2d4f6cfc240316114c6efad5b39ee2ee81de9ffb').replace(/['"]/g, '').trim();
  const cleanCode = (code || '').trim();

  const crypto = require('crypto');
  const httpFetch = require('../utils/httpHelper');
  const timestamp = Math.floor(Date.now() / 1000).toString();

  // Signature calculation payload for bg.open.accesstoken.create (all body fields included in MD5 calculation)
  const payload = {
    app_key: cleanKey,
    access_token: cleanCode,
    timestamp: timestamp,
    type: 'bg.open.accesstoken.create',
    code: cleanCode
  };

  const sortedKeys = Object.keys(payload).sort();
  const signStr = cleanSecret + sortedKeys.map(k => k + payload[k]).join('') + cleanSecret;
  const sign = crypto.createHash('md5').update(signStr).digest('hex').toUpperCase();

  const fullBody = {
    ...payload,
    sign
  };

  const routerUrl = process.env.TEMU_ROUTER_URL || 'https://openapi-b-eu.temu.com/openapi/router';

  try {
    console.log(`🔑 Temu OAuth: Exchanging code for access token via ${routerUrl}...`);

    const tokenRes = await httpFetch(routerUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(fullBody),
      timeout: 15000
    });

    const body = await tokenRes.json();
    console.log('📋 Temu token exchange response:', JSON.stringify(body));

    const isSuccess = body.success === true || body.errorCode === 1000000 || body.errorCode === 0;
    if (!isSuccess) {
      const errorDetail = body.errorMsg || body.error_msg || `Error code ${body.errorCode}`;
      console.warn(`❌ Temu token exchange failed: ${errorDetail}`);
      return res.redirect(`${frontendUrl}/settings?temu_error=${encodeURIComponent(errorDetail)}`);
    }

    // Extract access token and mall details
    const result = body.result || body.data || {};
    const accessToken = result.access_token || result.accessToken;
    const mallId = result.mall_id || result.mallId || '';
    const mallName = result.mall_name || result.mallName || '';
    const associatedMallTokenList = result.associatedMallTokenList || result.associated_mall_token_list || [];

    if (!accessToken) {
      console.warn('❌ Temu OAuth: access_token missing from response.');
      return res.redirect(`${frontendUrl}/settings?temu_error=no_access_token_in_response`);
    }

    console.log(`✅ Temu OAuth: Got primary access_token for mall ${mallId} (${mallName}) with ${associatedMallTokenList.length} associated regional store token(s).`);

    // Find the user via state parameter or fallback to primary user if initiated directly from Temu App Store
    const mongoose = require('mongoose');
    let user = null;
    if (state && mongoose.connection.readyState === 1) {
      user = await User.findById(state).catch(() => null);
    }
    if (!user && mongoose.connection.readyState === 1) {
      // Fallback if authorization was initiated directly from Temu Partner Platform Console
      user = await User.findOne({ role: 'admin' }) || await User.findOne({ email: process.env.SMTP_USER }) || await User.findOne();
    }

    if (!user) {
      console.warn(`❌ Temu OAuth: User not found for state=${state}`);
      return res.redirect(`${frontendUrl}/settings?temu_error=user_not_found`);
    }

    if (!user.temuIntegrations) user.temuIntegrations = [];

    // Build array of all store tokens to register (Primary store + all associated regional stores e.g. France, Italy, Spain, etc.)
    const storesToRegister = [
      {
        sellerId: mallId ? mallId.toString() : `Temu-${accessToken.slice(-6)}`,
        shopName: mallName || `Temu-${mallId || accessToken.slice(-6)}`,
        accessToken: accessToken
      }
    ];

    if (Array.isArray(associatedMallTokenList) && associatedMallTokenList.length > 0) {
      associatedMallTokenList.forEach(assoc => {
        const assocToken = assoc.accessToken || assoc.access_token;
        const assocMallId = (assoc.mallId || assoc.mall_id || '').toString();
        const assocMallName = assoc.mallName || assoc.mall_name || (assoc.regionName ? `Temu (${assoc.regionName})` : `Temu-${assocMallId}`);

        if (assocToken && !storesToRegister.some(s => s.accessToken === assocToken)) {
          storesToRegister.push({
            sellerId: assocMallId || `Temu-${assocToken.slice(-6)}`,
            shopName: assocMallName,
            accessToken: assocToken
          });
        }
      });
    }

    // Upsert all regional store integrations for the user
    for (const store of storesToRegister) {
      const integrationObj = {
        isConnected: true,
        appKey: cleanKey,
        appSecret: cleanSecret,
        accessToken: store.accessToken,
        sellerId: store.sellerId,
        shopName: store.shopName,
        lastSyncedAt: new Date()
      };

      const existingIdx = user.temuIntegrations.findIndex(i => i.accessToken === store.accessToken || (store.sellerId && i.sellerId === store.sellerId));
      if (existingIdx > -1) {
        user.temuIntegrations[existingIdx] = integrationObj;
      } else {
        user.temuIntegrations.push(integrationObj);
      }
    }

    // Keep single temuIntegration as legacy fallback pointing to primary store
    user.temuIntegration = user.temuIntegrations[0];
    await user.save();

    console.log(`✅ Temu OAuth: Saved ${storesToRegister.length} regional store integration(s) for user ${user.email}`);

    // Trigger background order sync
    try {
      const temuSyncService = require('../services/temuSync.service');
      temuSyncService.syncUserTemuOrders(user).catch(err =>
        console.warn('Post-OAuth Temu sync warning:', err.message)
      );
    } catch (syncErr) {
      console.warn('Post-OAuth sync init warning:', syncErr.message);
    }

    // Cache processed code to handle any duplicate GET requests from browser/proxy
    processedOAuthCodes.set(code, { status: 'success', mallName: mallName || mallId, timestamp: Date.now() });

    // Redirect back to frontend settings with success
    res.redirect(`${frontendUrl}/settings?temu_success=true&mall_name=${encodeURIComponent(mallName || mallId)}`);

  } catch (err) {
    console.error('💥 Temu OAuth callback exception:', err.message);
    res.redirect(`${frontendUrl}/settings?temu_error=${encodeURIComponent(err.message)}`);
  }
});

